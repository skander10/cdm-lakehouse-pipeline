"""Quality report: a readable summary of one pipeline run, for people (reports/).

Shows how many records arrived, how many were written, which were quarantined and why,
and where values were left empty or assumed. Record IDs only, never names or e-mail addresses.
"""

import logging
from pathlib import Path

import pandas as pd

from src.config import PipelineConfig
from src.extract import ExtractResult
from src.transform import DataIssue, TransformResult

logger = logging.getLogger(__name__)

REPORT_FILE = "data_quality_report.md"

# ---------------------------------------------------------------------------
# Part 1: count per entity
# ---------------------------------------------------------------------------


# Count for each entity: lines read, rows written, records quarantined, issues.
def summary_rows(
    customers: ExtractResult, orders: ExtractResult, result: TransformResult
) -> list[list[str]]:
    rows = []
    entities = [
        ("Contact", customers, result.contacts),
        ("SalesOrder", orders, result.sales_orders),
    ]
    for entity, extracted, table in entities:
        lines_read = len(extracted.data) + len(extracted.rejected)
        quarantined = len(extracted.rejected) + sum(
            1 for record in result.quarantined if record.entity == entity
        )
        issues = sum(1 for issue in result.issues if issue.entity == entity)
        rows.append([entity, str(lines_read), str(len(table)), str(quarantined), str(issues)])
    return rows


# ---------------------------------------------------------------------------
# Part 2: build the report text (Markdown, shown as formatted tables on GitHub)
# ---------------------------------------------------------------------------


# Turn a header and rows into a Markdown table.
def markdown_table(header: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "None."
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


# Build the whole report: summary, quarantined records, issues. IDs only, no raw values.
def build_report(
    summary: list[list[str]], quarantine: pd.DataFrame, issues: list[DataIssue]
) -> str:
    """quarantine is the table from load.quarantine_table, without raw_values (personal data)."""
    quarantine_rows = quarantine[["stage", "entity", "record_id", "reason"]].values.tolist()
    issue_rows = [[issue.entity, issue.record_id, issue.field, issue.message] for issue in issues]
    sections = [
        "# Data Quality Report",
        "Generated by the pipeline on every run. Record IDs only, no personal data.",
        "## Summary",
        markdown_table(["Entity", "Lines read", "Rows written", "Quarantined", "Issues"], summary),
        "## Quarantined records (not in the CDM tables)",
        markdown_table(["Stage", "Entity", "Record ID", "Reason"], quarantine_rows),
        "## Issues (record kept, value left empty or assumed)",
        markdown_table(["Entity", "Record ID", "Field", "Problem"], issue_rows),
    ]
    return "\n\n".join(sections) + "\n"


# ---------------------------------------------------------------------------
# Part 3: write the report
# ---------------------------------------------------------------------------


# Write the report to reports/data_quality_report.md, atomically (temporary file, then rename).
def write_report(report: str, config: PipelineConfig) -> Path:
    path = config.reports_dir / REPORT_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_path = path.with_name(path.name + ".tmp")
    temp_path.write_text(report, encoding="utf-8")
    temp_path.replace(path)  # one step: readers see the old file or the new one, never half
    logger.info("Quality report written to %s", path.name)
    return path
